// Package timesys 是 IriX 节点的自有时间系统。
//
// 节点不再信任系统墙钟：它用 Roughtime（RFC 10049，同时兼容已部署的旧格式）
// 从多台互相独立的服务器获取带签名、带半径的时间区间，再由本包完成
//
//   - 漂移补偿：对 (单调时钟, 真值) 样本做最小二乘拟合，估计本机晶振频率误差
//     （ppm），持续校正虚拟时钟的推进速率；
//   - 时钟纪律：小误差按 NTP 风格 slew（默认上限 500ppm，绝不回拨业务时间），
//     大误差才步进；每轮同步做多源一致性判定，孤立/说谎的服务器不被采信；
//   - 保持（holdover）：同步中断时按漂移上界增长不确定度，并把锚点/频率校正
//     落盘，重启后继续推算；
//   - 不确定度：对外暴露当前时间误差上界与可信判定，供 TLS、会话、审计等
//     安全相关路径决定是否采信当前时间。
//
// 业务代码通过包级 Now()/Since()/Until() 使用同一时间源；测试可用
// NewFakeClock + SetCurrent 接管整条时间链路。
